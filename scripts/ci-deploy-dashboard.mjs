#!/usr/bin/env node
/**
 * scripts/ci-deploy-dashboard.mjs
 * Deploys CI health HTML dashboard to docs/ci-dashboard/ and commits.
 *
 * Usage:
 *   node scripts/ci-deploy-dashboard.mjs        # deploy
 *   node scripts/ci-deploy-dashboard.mjs --dry  # preview only
 */
import { spawn } from 'child_process';
import { existsSync, mkdirSync, writeFileSync, readFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const DOCS_DIR = join(ROOT, 'docs', 'ci-dashboard');
const OUTPUT_HTML = join(DOCS_DIR, 'index.html');

const DRY = process.argv.includes('--dry');

function run(cmd, args) {
  return new Promise((resolve, reject) => {
    const p = spawn(cmd, args, { shell: true, cwd: ROOT, stdio: 'pipe' });
    let out = '', err = '';
    p.stdout.on('data', d => out += d.toString());
    p.stderr.on('data', d => err += d.toString());
    p.on('close', code => resolve({ code, out, err }));
    p.on('error', reject);
  });
}

async function main() {
  // 1. Ensure docs/ci-dashboard/ exists
  if (!existsSync(DOCS_DIR)) {
    if (DRY) {
      console.log('[dry] Would create:', DOCS_DIR);
    } else {
      mkdirSync(DOCS_DIR, { recursive: true });
      console.log('Created:', DOCS_DIR);
    }
  }

  // 2. Generate HTML from hreport
  if (DRY) {
    console.log('[dry] Would run: node scripts/ci-health-report.mjs > index.html');
  } else {
    const { code, out, err } = await run('node', ['scripts/ci-health-report.mjs']);
    if (code !== 0) {
      console.error('Failed to generate report:', err);
      process.exit(1);
    }
    writeFileSync(OUTPUT_HTML, out);
    console.log('Written:', OUTPUT_HTML);
  }

  // 3. Check git status
  if (DRY) {
    console.log('[dry] Would check git status');
    console.log('[dry] Would add + commit + push to main');
    console.log('[dry] Note: GitHub Pages must be configured to serve from /docs on main branch');
    return;
  }

  const { code: sCode } = await run('git', ['status', '--porcelain', 'docs/ci-dashboard/']);
  if (sCode === 0) {
    // 4. Git add + commit
    await run('git', ['add', 'docs/ci-dashboard/']);
    const { out: diffOut } = await run('git', ['diff', '--cached', '--stat', 'docs/ci-dashboard/']);
    console.log('Staged:', diffOut.trim());

    const date = new Date().toISOString().split('T')[0];
    const msg = `docs: update CI health dashboard ${date}\n\nAuto-generated by scripts/ci-deploy-dashboard.mjs`;
    const { code: cCode, err: cErr } = await run('git', ['commit', '-m', msg]);
    if (cCode !== 0) {
      console.error('Commit failed:', cErr);
      process.exit(1);
    }
    console.log('Committed to main branch');

    // 5. Push
    const { code: pCode, err: pErr } = await run('git', ['push', 'origin', 'main']);
    if (pCode !== 0) {
      console.error('Push failed:', pErr);
      process.exit(1);
    }
    console.log('Pushed to origin/main');
    console.log('\n✅ Dashboard deployed!');
    console.log('   GitHub Pages: https://<username>.github.io/<repo>/ci-dashboard/');
    console.log('   (Enable GitHub Pages: Settings → Pages → Source: main branch /docs folder)');
  } else {
    console.log('No changes to docs/ci-dashboard — already up to date.');
  }
}

main().catch(e => { console.error(e); process.exit(1); });
