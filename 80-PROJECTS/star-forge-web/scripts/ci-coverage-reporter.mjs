/**
 * scripts/ci-coverage-reporter.mjs — Generate CI coverage report for GitHub PR comments
 * Run: node scripts/ci-coverage-reporter.mjs [--json]
 *
 * Parses coverage/coverage-final.json, outputs summary JSON or markdown table.
 * Designed to be called from GitHub Actions CI.
 */
import { readFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const IS_JSON = process.argv.includes('--json');

function parseFileCoverage(filePath, data) {
  const f = data[filePath];
  if (!f) return null;
  const sVals = Object.values(f.s || {});
  const sCovered = sVals.filter(v => v > 0).length;
  const stmts = sVals.length ? Math.round((sCovered / sVals.length) * 1000) / 10 : 0;
  const fVals = Object.values(f.fnMap || {});
  const fCovered = fVals.filter(v => v.exec > 0).length;
  const funcs = fVals.length ? Math.round((fCovered / fVals.length) * 1000) / 10 : 0;
  const bChildKeys = Object.values(f.b || {}).flat();
  const bCovered = bChildKeys.filter(v => v > 0).length;
  const branches = bChildKeys.length ? Math.round((bCovered / bChildKeys.length) * 1000) / 10 : 0;
  return { lines: stmts, statements: stmts, functions: funcs, branches };
}

function parseCoverageFinal() {
  const data = JSON.parse(readFileSync(join(ROOT, 'coverage/coverage-final.json'), 'utf8'));
  const files = Object.keys(data);
  const summaries = [];
  for (const file of files) {
    const cov = parseFileCoverage(file, data);
    if (cov) {
      summaries.push({
        file: file.replace(/^coverage\//, ''),
        ...cov,
      });
    }
  }
  return summaries;
}

function overallSummary(summaries) {
  if (!summaries.length) return { lines: 0, statements: 0, functions: 0, branches: 0 };
  const lines = Math.round(summaries.reduce((s, r) => s + r.lines, 0) / summaries.length * 10) / 10;
  const statements = Math.round(summaries.reduce((s, r) => s + r.statements, 0) / summaries.length * 10) / 10;
  const functions = Math.round(summaries.reduce((s, r) => s + r.functions, 0) / summaries.length * 10) / 10;
  const branches = Math.round(summaries.reduce((s, r) => s + r.branches, 0) / summaries.length * 10) / 10;
  return { lines, statements, functions, branches };
}

const summaries = parseCoverageFinal();
const overall = overallSummary(summaries);
const totalFiles = summaries.length;

if (IS_JSON) {
  console.log(JSON.stringify({ overall, totalFiles, files: summaries }, null, 2));
} else {
  console.log('\n  ── star-forge Coverage ──');
  console.log(`  Files:  ${totalFiles}`);
  console.log(`  Lines:  ${overall.lines}%`);
  console.log(`  Stmts:  ${overall.statements}%`);
  console.log(`  Funcs:  ${overall.functions}%`);
  console.log(`  Branch: ${overall.branches}%`);
  console.log('\n  File Details');
  console.log('  ─────────────────────');
  for (const s of summaries) {
    console.log(`  ${String(s.lines).padStart(5)}%  ${s.file}`);
  }
  console.log('');

  // Markdown table for GitHub PR comment
  const md = `## Coverage Summary

| Metric | Value |
|--------|-------|
| Lines | ${overall.lines}% |
| Statements | ${overall.statements}% |
| Functions | ${overall.functions}% |
| Branches | ${overall.branches}% |
| Files | ${totalFiles} |

| File | Lines % | Stmts % | Funcs % | Branch % |
|------|---------|---------|---------|---------|
${summaries.map(s => `| ${s.file} | ${s.lines}% | ${s.statements}% | ${s.functions}% | ${s.branches}% |`).join('\n')}

*Generated by scripts/ci-coverage-reporter.mjs*`;
  console.log('---GITHUB_PR_COMMENT---');
  console.log(md);
  console.log('---');
}
